//! Font programs as FreeType presents them to MuPDF: a [`Face`] has a
//! format, glyphs, charmaps (the font's own and the ones FreeType
//! synthesizes), glyph names and advances. The program is parsed here; no
//! glyph is rendered.

pub mod cff;
// Generated by `cargo xtask tables`, byte for byte.
#[rustfmt::skip]
pub mod names;
pub mod sfnt;
pub mod type1;

use std::sync::Arc;

use crate::glyphs;

/// `FT_Get_Font_Format`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    TrueType,
    Type1,
    Cff,
}

/// The encoding FreeType gives a charmap.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Encoding {
    Unicode,
    MsSymbol,
    AppleRoman,
    AdobeStandard,
    AdobeExpert,
    AdobeCustom,
    AdobeLatin1,
    Other,
}

#[derive(Debug, Clone)]
enum Source {
    /// An sfnt `cmap` subtable.
    Sfnt(usize),
    /// Synthesized from glyph names: (code point, glyph), sorted.
    Unicode(Arc<Vec<(u32, u32)>>),
    /// A Type 1 standard or expert encoding: code to glyph.
    Codes(Arc<Vec<u32>>),
    /// A CFF font's own encoding.
    CffCodes,
}

#[derive(Debug, Clone)]
pub struct Charmap {
    pub platform_id: u16,
    pub encoding_id: u16,
    pub encoding: Encoding,
    source: Source,
}

#[derive(Debug, Clone)]
enum Program {
    Sfnt(sfnt::Sfnt),
    Cff(Box<cff::Cff>),
    Type1(type1::Type1),
}

/// An `FT_Face`.
#[derive(Debug, Clone)]
pub struct Face {
    pub format: Format,
    pub num_glyphs: u32,
    pub units_per_em: u16,
    pub ascender: i16,
    pub descender: i16,
    pub bbox: [i32; 4],
    pub has_glyph_names: bool,
    pub cid_keyed: bool,
    pub charmaps: Vec<Charmap>,
    /// The selected charmap.
    pub charmap: Option<usize>,
    program: Program,
}

/// `ps_unicode_value`: a glyph name's code point, with the variant flag
/// for a suffixed name.
fn ps_unicode(name: &[u8]) -> Option<(u32, bool)> {
    let hex = |s: &[u8]| -> Option<u32> {
        let mut v = 0u32;
        for &c in s {
            v = v * 16 + char::from(c).to_digit(16)?;
        }
        Some(v)
    };
    if let Some(rest) = name.strip_prefix(b"uni")
        && rest.len() >= 4
        && let Some(v) = hex(&rest[..4])
        && (rest.len() == 4 || rest[4] == b'.')
    {
        return Some((v, rest.len() > 4));
    }
    if let Some(rest) = name.strip_prefix(b"u") {
        let digits = rest
            .iter()
            .take(6)
            .take_while(|c| c.is_ascii_hexdigit())
            .count();
        if digits >= 4
            && let Some(v) = hex(&rest[..digits])
            && (rest.len() == digits || rest[digits] == b'.')
        {
            return Some((v, rest.len() > digits));
        }
    }
    let dot = name.iter().position(|&c| c == b'.').unwrap_or(name.len());
    if dot == 0 {
        return None;
    }
    let v = glyphs::unicode_strict(&name[..dot]);
    (v != 0).then_some((v, dot < name.len()))
}

/// `ps_unicodes_init`: the Unicode charmap of a font with glyph names,
/// None when no name maps to a code point.
fn synthesize_unicode(names: impl Iterator<Item = (u32, Vec<u8>)>) -> Option<Arc<Vec<(u32, u32)>>> {
    let mut map: Vec<(u32, bool, u32)> = names
        .filter_map(|(g, n)| ps_unicode(&n).map(|(u, variant)| (u, variant, g)))
        .collect();
    if map.is_empty() {
        return None;
    }
    // Plain names before suffixed ones, the first glyph before later ones.
    map.sort_by_key(|&(u, variant, g)| (u, variant, g));
    map.dedup_by_key(|e| e.0);
    Some(Arc::new(map.into_iter().map(|(u, _, g)| (u, g)).collect()))
}

impl Face {
    /// `FT_New_Memory_Face` with face index 0, trying the TrueType, Type 1
    /// and CFF drivers in MuPDF's order. The error is FreeType's name.
    pub fn open(data: Arc<[u8]>) -> Result<Face, &'static str> {
        if sfnt::Sfnt::recognize(&data) {
            let s = sfnt::Sfnt::open(data.clone())?;
            let tag = data.get(0..4).unwrap_or_default();
            let ttc_true = tag == b"ttcf" && s.has_glyf;
            if tag == [0, 1, 0, 0] || tag == b"true" || ttc_true {
                return Ok(Self::from_sfnt(s, Format::TrueType));
            }
            if s.has_cff {
                return Ok(Self::from_sfnt(s, Format::Cff));
            }
            return Err("Unknown_File_Format");
        }
        if type1::Type1::recognize(&data) {
            return Ok(Self::from_type1(type1::Type1::open(data)?));
        }
        if cff::Cff::recognize(&data) {
            return Ok(Self::from_cff(cff::Cff::open(data)?));
        }
        Err("Unknown_File_Format")
    }

    fn from_sfnt(s: sfnt::Sfnt, format: Format) -> Face {
        let mut charmaps: Vec<Charmap> = s
            .subtables
            .iter()
            .enumerate()
            .map(|(i, t)| Charmap {
                platform_id: t.platform_id,
                encoding_id: t.encoding_id,
                encoding: sfnt::encoding_of(t.platform_id, t.encoding_id),
                source: Source::Sfnt(i),
            })
            .collect();
        let has_unicode = charmaps
            .iter()
            .any(|c| matches!(c.encoding, Encoding::Unicode | Encoding::MsSymbol));
        if !has_unicode
            && s.has_glyph_names()
            && let Some(map) = synthesize_unicode(
                (0..s.num_glyphs).filter_map(|g| s.glyph_name(g).map(|n| (g, n))),
            )
        {
            charmaps.push(Charmap {
                platform_id: 3,
                encoding_id: 1,
                encoding: Encoding::Unicode,
                source: Source::Unicode(map),
            });
        }
        let mut face = Face {
            format,
            num_glyphs: s.num_glyphs,
            units_per_em: s.units_per_em,
            ascender: s.ascender,
            descender: s.descender,
            bbox: s.bbox,
            has_glyph_names: s.has_glyph_names(),
            cid_keyed: false,
            charmaps,
            charmap: None,
            program: Program::Sfnt(s),
        };
        face.select_default();
        face
    }

    fn from_type1(t: type1::Type1) -> Face {
        let n = t.names.len() as u32;
        let mut charmaps = Vec::new();
        if let Some(map) = synthesize_unicode(
            t.names
                .iter()
                .cloned()
                .enumerate()
                .map(|(g, n)| (g as u32, n)),
        ) {
            charmaps.push(Charmap {
                platform_id: 3,
                encoding_id: 1,
                encoding: Encoding::Unicode,
                source: Source::Unicode(map),
            });
        }
        let std_codes = |table: &[u16; 256]| -> Arc<Vec<u32>> {
            Arc::new(
                table
                    .iter()
                    .map(|&sid| {
                        let name = names::SID_NAMES
                            .get(usize::from(sid))
                            .copied()
                            .unwrap_or("");
                        t.names
                            .iter()
                            .position(|g| g.as_slice() == name.as_bytes())
                            .map_or(0, |g| g as u32)
                    })
                    .collect(),
            )
        };
        let adobe = match &t.encoding {
            type1::Encoding::Standard => Some((
                0,
                Encoding::AdobeStandard,
                Source::Codes(std_codes(&names::STANDARD_ENCODING)),
            )),
            type1::Encoding::Expert => Some((
                1,
                Encoding::AdobeExpert,
                Source::Codes(std_codes(&names::EXPERT_ENCODING)),
            )),
            type1::Encoding::Array { indices, count } => {
                let codes: Vec<u32> = (0..256u32)
                    .map(|c| {
                        if c < *count {
                            u32::from(*indices.get(c as usize).unwrap_or(&0))
                        } else {
                            0
                        }
                    })
                    .collect();
                Some((2, Encoding::AdobeCustom, Source::Codes(Arc::new(codes))))
            }
            type1::Encoding::IsoLatin1 => synthesize_unicode(
                t.names
                    .iter()
                    .cloned()
                    .enumerate()
                    .map(|(g, n)| (g as u32, n)),
            )
            .map(|m| (3, Encoding::AdobeLatin1, Source::Unicode(m))),
            type1::Encoding::None => None,
        };
        if let Some((id, encoding, source)) = adobe {
            charmaps.push(Charmap {
                platform_id: 7,
                encoding_id: id,
                encoding,
                source,
            });
        }
        let bbox = t.bbox;
        let mut face = Face {
            format: Format::Type1,
            num_glyphs: n,
            units_per_em: t.units_per_em,
            ascender: bbox[3] as i16,
            descender: bbox[1] as i16,
            bbox,
            has_glyph_names: true,
            cid_keyed: false,
            charmaps,
            charmap: None,
            program: Program::Type1(t),
        };
        face.select_default();
        face
    }

    fn from_cff(c: cff::Cff) -> Face {
        let num_glyphs = if c.is_cid {
            c.max_cid() + 1
        } else {
            c.num_glyphs()
        };
        let mut charmaps = Vec::new();
        if !c.is_cid {
            if let Some(map) = synthesize_unicode(
                (0..c.num_glyphs()).filter_map(|g| c.glyph_name(g).map(|n| (g, n))),
            ) {
                charmaps.push(Charmap {
                    platform_id: 3,
                    encoding_id: 1,
                    encoding: Encoding::Unicode,
                    source: Source::Unicode(map),
                });
            }
            if c.encoding_count > 0 {
                let (id, encoding) = match c.encoding_offset {
                    0 => (0, Encoding::AdobeStandard),
                    1 => (1, Encoding::AdobeExpert),
                    _ => (2, Encoding::AdobeCustom),
                };
                charmaps.push(Charmap {
                    platform_id: 7,
                    encoding_id: id,
                    encoding,
                    source: Source::CffCodes,
                });
            }
        }
        let bbox = c.bbox;
        let mut face = Face {
            format: Format::Cff,
            num_glyphs,
            units_per_em: c.units_per_em.min(u32::from(u16::MAX)) as u16,
            ascender: bbox[3] as i16,
            descender: bbox[1] as i16,
            bbox,
            has_glyph_names: !c.is_cid,
            cid_keyed: c.is_cid,
            charmaps,
            charmap: None,
            program: Program::Cff(Box::new(c)),
        };
        face.select_default();
        face
    }

    /// `find_unicode_charmap`, as FT_Open_Face selects a charmap: a
    /// UCS-4 one from the end, else any Unicode one from the end.
    fn select_default(&mut self) {
        let ucs4 = self.charmaps.iter().rposition(|c| {
            c.encoding == Encoding::Unicode
                && ((c.platform_id == 3 && c.encoding_id == 10)
                    || (c.platform_id == 0 && c.encoding_id == 4))
        });
        self.charmap = ucs4.or_else(|| {
            self.charmaps
                .iter()
                .rposition(|c| c.encoding == Encoding::Unicode)
        });
    }

    /// `FT_Select_Charmap(face, FT_ENCODING_UNICODE)`: false when there is
    /// no Unicode charmap.
    pub fn select_unicode(&mut self) -> bool {
        let before = self.charmap;
        self.select_default();
        if self
            .charmap
            .is_some_and(|i| self.charmaps[i].encoding == Encoding::Unicode)
        {
            true
        } else {
            self.charmap = before;
            false
        }
    }

    /// `FT_Get_CMap_Format`: -1 for a charmap that is not an sfnt subtable.
    pub fn cmap_format(&self, i: usize) -> i32 {
        match (&self.program, self.charmaps.get(i).map(|c| &c.source)) {
            (Program::Sfnt(s), Some(Source::Sfnt(t))) => {
                s.subtables.get(*t).map_or(-1, |t| i32::from(t.format))
            }
            _ => -1,
        }
    }

    /// `FT_Get_Char_Index` with the selected charmap.
    pub fn get_char_index(&self, code: u32) -> u32 {
        let Some(cm) = self.charmap.and_then(|i| self.charmaps.get(i)) else {
            return 0;
        };
        let g = match (&cm.source, &self.program) {
            (Source::Sfnt(i), Program::Sfnt(s)) => {
                s.subtables.get(*i).map_or(0, |t| s.char_index(t, code))
            }
            (Source::Unicode(map), _) => map
                .binary_search_by_key(&code, |&(u, _)| u)
                .map_or(0, |i| map[i].1),
            (Source::Codes(codes), _) => codes.get(code as usize).copied().unwrap_or(0),
            (Source::CffCodes, Program::Cff(c)) => {
                c.codes.get(code as usize).map_or(0, |&g| u32::from(g))
            }
            _ => 0,
        };
        if g >= self.num_glyphs { 0 } else { g }
    }

    /// MuPDF's `ft_char_index`: the code, then the code in the symbol
    /// area, then a lookalike for U+22EF.
    pub fn char_index(&self, code: u32) -> u32 {
        let mut g = self.get_char_index(code);
        if g == 0 {
            g = self.get_char_index(0xf000u32.wrapping_add(code));
        }
        if g == 0 && code == 0x22ef {
            g = self.get_char_index(0x2026);
        }
        g
    }

    /// `FT_Get_Name_Index`.
    pub fn get_name_index(&self, name: &[u8]) -> u32 {
        match &self.program {
            Program::Sfnt(s) => s.name_index(name),
            Program::Cff(c) => c.name_index(name),
            Program::Type1(t) => t.name_index(name),
        }
    }

    /// MuPDF's `ft_name_index`: the name, then other names of its code
    /// point, then `uniXXXX`.
    pub fn name_index(&self, name: &[u8]) -> u32 {
        let code = self.get_name_index(name);
        if code != 0 {
            return code;
        }
        let unicode = glyphs::unicode(name);
        if unicode == 0 {
            return 0;
        }
        for dup in glyphs::duplicate_names(unicode) {
            let c = self.get_name_index(dup.as_bytes());
            if c != 0 {
                return c;
            }
        }
        self.get_name_index(format!("uni{unicode:04X}").as_bytes())
    }

    /// `FT_Get_Glyph_Name`, None for a face without names.
    pub fn glyph_name(&self, gid: u32) -> Option<Vec<u8>> {
        match &self.program {
            Program::Sfnt(s) => s.glyph_name(gid),
            Program::Cff(c) => c.glyph_name(gid),
            Program::Type1(t) => t.glyph_name(gid),
        }
    }

    /// `FT_Get_Advance` unscaled: the advance in font units, None where
    /// FreeType fails (a glyph that does not exist).
    pub fn advance(&self, gid: u32) -> Option<i64> {
        if gid >= self.num_glyphs {
            return None;
        }
        match &self.program {
            Program::Sfnt(s) if self.format == Format::TrueType => Some(i64::from(s.advance(gid))),
            Program::Sfnt(s) => Some(i64::from(s.advance(gid))),
            Program::Cff(c) => {
                let g = if c.is_cid { c.gid_of_cid(gid) } else { gid };
                c.advance(g).map(|a| a.round() as i64)
            }
            Program::Type1(t) => t.advance(gid),
        }
    }

    /// The format string FreeType reports.
    pub fn format_name(&self) -> &'static str {
        match self.format {
            Format::TrueType => "TrueType",
            Format::Type1 => "Type 1",
            Format::Cff => "CFF",
        }
    }
}

/// `fz_lookup_base14_font`: MuPDF's builtin font for a standard name.
pub fn base14(name: &str) -> Option<&'static [u8]> {
    Some(match name {
        "Courier" => include_bytes!("../../fonts/urw/NimbusMonoPS-Regular.cff"),
        "Courier-Oblique" => include_bytes!("../../fonts/urw/NimbusMonoPS-Italic.cff"),
        "Courier-Bold" => include_bytes!("../../fonts/urw/NimbusMonoPS-Bold.cff"),
        "Courier-BoldOblique" => include_bytes!("../../fonts/urw/NimbusMonoPS-BoldItalic.cff"),
        "Helvetica" => include_bytes!("../../fonts/urw/NimbusSans-Regular.cff"),
        "Helvetica-Oblique" => include_bytes!("../../fonts/urw/NimbusSans-Italic.cff"),
        "Helvetica-Bold" => include_bytes!("../../fonts/urw/NimbusSans-Bold.cff"),
        "Helvetica-BoldOblique" => include_bytes!("../../fonts/urw/NimbusSans-BoldItalic.cff"),
        "Times-Roman" => include_bytes!("../../fonts/urw/NimbusRoman-Regular.cff"),
        "Times-Italic" => include_bytes!("../../fonts/urw/NimbusRoman-Italic.cff"),
        "Times-Bold" => include_bytes!("../../fonts/urw/NimbusRoman-Bold.cff"),
        "Times-BoldItalic" => include_bytes!("../../fonts/urw/NimbusRoman-BoldItalic.cff"),
        "Symbol" => include_bytes!("../../fonts/urw/StandardSymbolsPS.cff"),
        "ZapfDingbats" => include_bytes!("../../fonts/urw/Dingbats.cff"),
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_base_fonts_open_as_cff_with_their_encodings() {
        let data: Arc<[u8]> = base14("Helvetica").unwrap_or_default().into();
        let face = Face::open(data).unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(face.format, Format::Cff);
        assert_eq!(face.units_per_em, 1000);
        assert!(face.num_glyphs > 200);
        let a = face.get_name_index(b"A");
        assert!(a > 0);
        assert_eq!(face.glyph_name(a).as_deref(), Some(&b"A"[..]));
        // The Unicode charmap is the default.
        assert_eq!(face.char_index(0x41), a);
        // NimbusSans' A is 667 units wide, as Helvetica's.
        assert_eq!(face.advance(a), Some(667));
        assert!(face.charmaps.iter().any(|c| c.platform_id == 7));
    }

    #[test]
    fn suffixed_names_map_after_plain_ones() {
        assert_eq!(ps_unicode(b"uni0041"), Some((0x41, false)));
        assert_eq!(ps_unicode(b"a.sc"), Some((0x61, true)));
        assert_eq!(ps_unicode(b"u1F600"), Some((0x1f600, false)));
        assert_eq!(ps_unicode(b".notdef"), None);
    }
}
