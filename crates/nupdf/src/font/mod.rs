/// `FT_MulDiv`: `a * b / c`, rounded.
fn mul_div(a: i64, b: i64, c: i64) -> i64 {
    if c == 0 {
        return 0x7FFF_FFFF;
    }
    let s = ((a < 0) != (b < 0)) != (c < 0);
    let (a, b, c) = (a.unsigned_abs(), b.unsigned_abs(), c.unsigned_abs());
    let d = (a * b + (c >> 1)) / c;
    if s { -(d as i64) } else { d as i64 }
}

