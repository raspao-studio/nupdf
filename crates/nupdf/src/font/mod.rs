//! Font programs as FreeType presents them to MuPDF: a [`Face`] has a
//! format, glyphs, charmaps (the font's own and the ones FreeType
//! synthesizes), glyph names and advances. The program is parsed here; no
//! glyph is rendered.

pub mod cff;
// Generated by `cargo xtask tables`, byte for byte.
#[rustfmt::skip]
pub mod names;
pub mod outline;
pub mod sfnt;
pub mod type1;

use std::sync::Arc;

use crate::glyphs;

/// `FT_Get_Font_Format`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    TrueType,
    Type1,
    Cff,
}

/// The encoding FreeType gives a charmap.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Encoding {
    Unicode,
    MsSymbol,
    AppleRoman,
    AdobeStandard,
    AdobeExpert,
    AdobeCustom,
    AdobeLatin1,
    Other,
}

#[derive(Debug, Clone)]
enum Source {
    /// An sfnt `cmap` subtable.
    Sfnt(usize),
    /// Synthesized from glyph names: (code point, glyph), sorted.
    Unicode(Arc<Vec<(u32, u32)>>),
    /// A Type 1 standard or expert encoding: code to glyph.
    Codes(Arc<Vec<u32>>),
    /// A CFF font's own encoding.
    CffCodes,
}

#[derive(Debug, Clone)]
pub struct Charmap {
    pub platform_id: u16,
    pub encoding_id: u16,
    pub encoding: Encoding,
    source: Source,
}

#[derive(Debug, Clone)]
enum Program {
    Sfnt(sfnt::Sfnt),
    Cff(Box<cff::Cff>),
    Type1(type1::Type1),
}

/// An `FT_Face`.
#[derive(Debug, Clone)]
pub struct Face {
    pub format: Format,
    pub num_glyphs: u32,
    pub units_per_em: u16,
    pub ascender: i16,
    pub descender: i16,
    pub bbox: [i32; 4],
    pub has_glyph_names: bool,
    pub cid_keyed: bool,
    pub charmaps: Vec<Charmap>,
    /// The selected charmap.
    pub charmap: Option<usize>,
    /// FT_STYLE_FLAG_BOLD, FT_STYLE_FLAG_ITALIC, FT_FACE_FLAG_FIXED_WIDTH.
    pub bold: bool,
    pub italic: bool,
    pub fixed_width: bool,
    /// The OS/2 table's sFamilyClass, for an sfnt that has the table.
    pub family_class: Option<i16>,
    program: Program,
}

/// `ps_unicode_value`: a glyph name's code point, with the variant flag
/// for a suffixed name.
fn ps_unicode(name: &[u8]) -> Option<(u32, bool)> {
    let hex = |s: &[u8]| -> Option<u32> {
        let mut v = 0u32;
        for &c in s {
            v = v * 16 + char::from(c).to_digit(16)?;
        }
        Some(v)
    };
    if let Some(rest) = name.strip_prefix(b"uni")
        && rest.len() >= 4
        && let Some(v) = hex(&rest[..4])
        && (rest.len() == 4 || rest[4] == b'.')
    {
        return Some((v, rest.len() > 4));
    }
    if let Some(rest) = name.strip_prefix(b"u") {
        let digits = rest
            .iter()
            .take(6)
            .take_while(|c| c.is_ascii_hexdigit())
            .count();
        if digits >= 4
            && let Some(v) = hex(&rest[..digits])
            && (rest.len() == digits || rest[digits] == b'.')
        {
            return Some((v, rest.len() > digits));
        }
    }
    let dot = name.iter().position(|&c| c == b'.').unwrap_or(name.len());
    if dot == 0 {
        return None;
    }
    let v = glyphs::unicode_strict(&name[..dot]);
    (v != 0).then_some((v, dot < name.len()))
}

/// The flag `ps_unicode_value` sets on the code point of a suffixed name.
const VARIANT: u32 = 0x8000_0000;

/// `ft_extra_glyph_names` and `_unicodes`: names the Adobe Glyph List
/// maps elsewhere, and the code point each also stands for.
const EXTRA_GLYPHS: [(&[u8], u32); 10] = [
    (b"Delta", 0x0394),
    (b"Omega", 0x03A9),
    (b"fraction", 0x2215),
    (b"hyphen", 0x00AD),
    (b"macron", 0x02C9),
    (b"mu", 0x03BC),
    (b"periodcentered", 0x2219),
    (b"space", 0x00A0),
    (b"Tcommaaccent", 0x021A),
    (b"tcommaaccent", 0x021B),
];

/// `ps_unicodes_init`: the Unicode charmap of a font with glyph names,
/// None when no name maps to a code point. Entries keep the variant flag;
/// duplicates stay, in glyph order.
fn synthesize_unicode(names: impl Iterator<Item = (u32, Vec<u8>)>) -> Option<Arc<Vec<(u32, u32)>>> {
    // Per extra glyph: unseen, its first glyph, or mapped by a name.
    let mut extra: [Option<Option<u32>>; 10] = [None; 10];
    let mut map: Vec<(u32, u32)> = Vec::new();
    for (g, n) in names {
        if n.is_empty() {
            continue;
        }
        if let Some(k) = EXTRA_GLYPHS.iter().position(|e| e.0 == n.as_slice())
            && extra[k].is_none()
        {
            extra[k] = Some(Some(g));
        }
        if let Some((u, variant)) = ps_unicode(&n) {
            if let Some(k) = EXTRA_GLYPHS.iter().position(|e| !variant && e.1 == u) {
                extra[k] = Some(None);
            }
            map.push((if variant { u | VARIANT } else { u }, g));
        }
    }
    for (e, state) in EXTRA_GLYPHS.iter().zip(extra) {
        if let Some(Some(g)) = state {
            map.push((e.1, g));
        }
    }
    if map.is_empty() {
        return None;
    }
    // compare_uni_maps: by code point, plain names before suffixed ones.
    map.sort_by_key(|&(u, _)| (u & !VARIANT, u));
    Some(Arc::new(map))
}

/// `ps_unicodes_char_index`: FreeType's search, which takes the plain
/// entry it meets first, else the last suffixed one it passed.
fn unicode_index(map: &[(u32, u32)], unicode: u32) -> u32 {
    let (mut min, mut max) = (0usize, map.len());
    let mut mid = max / 2;
    let mut result = None;
    while min < max {
        let (u, g) = map[mid];
        if u == unicode {
            result = Some(g);
            break;
        }
        let base = u & !VARIANT;
        if base == unicode {
            result = Some(g);
        }
        if base < unicode {
            min = mid + 1;
        } else {
            max = mid;
        }
        // A guess for a continuous block, when it falls in the range.
        mid = unicode
            .checked_sub(base)
            .and_then(|d| mid.checked_add(d as usize))
            .filter(|&m| m >= min && m < max)
            .unwrap_or(min + (max - min) / 2);
    }
    result.unwrap_or(0)
}

impl Face {
    /// `FT_New_Memory_Face` with face index 0, trying the TrueType, Type 1
    /// and CFF drivers in MuPDF's order. The error is FreeType's name.
    pub fn open(data: Arc<[u8]>) -> Result<Face, &'static str> {
        if sfnt::Sfnt::recognize(&data) {
            // FT_Open_Face reports a read past the end as no known format.
            let s = sfnt::Sfnt::open(data.clone()).map_err(|e| match e {
                "Invalid_Stream_Operation" => "Unknown_File_Format",
                e => e,
            })?;
            // The TrueType driver takes its version tags (a collection's
            // by its first font), the CFF driver the rest.
            if matches!(
                s.format_tag,
                sfnt::TAG_TRUETYPE | sfnt::TAG_TRUETYPE_CJK | sfnt::TAG_TRUE
            ) {
                s.check_loca()?;
                return Ok(Self::from_sfnt(s, Format::TrueType));
            }
            if s.format_tag != sfnt::TAG_OTTO {
                return Err("Unknown_File_Format");
            }
            if !s.has_cff {
                return Err("Table_Missing");
            }
            return Ok(Self::from_sfnt(s, Format::Cff));
        }
        if type1::Type1::recognize(&data) {
            return Ok(Self::from_type1(type1::Type1::open(data)?));
        }
        if cff::Cff::recognize(&data) {
            return Ok(Self::from_cff(cff::Cff::open(data)?));
        }
        Err("Unknown_File_Format")
    }

    fn from_sfnt(s: sfnt::Sfnt, format: Format) -> Face {
        let mut charmaps: Vec<Charmap> = s
            .subtables
            .iter()
            .enumerate()
            .map(|(i, t)| Charmap {
                platform_id: t.platform_id,
                encoding_id: t.encoding_id,
                encoding: sfnt::encoding_of(t.platform_id, t.encoding_id),
                source: Source::Sfnt(i),
            })
            .collect();
        let has_unicode = charmaps
            .iter()
            .any(|c| matches!(c.encoding, Encoding::Unicode | Encoding::MsSymbol));
        if !has_unicode
            && s.has_glyph_names()
            && let Some(map) = synthesize_unicode(
                (0..s.num_glyphs).filter_map(|g| s.glyph_name(g).map(|n| (g, n))),
            )
        {
            charmaps.push(Charmap {
                platform_id: 3,
                encoding_id: 1,
                encoding: Encoding::Unicode,
                source: Source::Unicode(map),
            });
        }
        let mut face = Face {
            format,
            num_glyphs: s.num_glyphs,
            units_per_em: s.units_per_em,
            ascender: s.ascender,
            descender: s.descender,
            bbox: s.bbox,
            has_glyph_names: s.has_glyph_names(),
            cid_keyed: false,
            charmaps,
            charmap: None,
            bold: s.bold,
            italic: s.italic,
            fixed_width: s.fixed_pitch,
            family_class: s.family_class,
            program: Program::Sfnt(s),
        };
        face.select_default();
        face
    }

    fn from_type1(t: type1::Type1) -> Face {
        let n = t.names.len() as u32;
        let mut charmaps = Vec::new();
        if let Some(map) = synthesize_unicode(
            t.names
                .iter()
                .cloned()
                .enumerate()
                .map(|(g, n)| (g as u32, n)),
        ) {
            charmaps.push(Charmap {
                platform_id: 3,
                encoding_id: 1,
                encoding: Encoding::Unicode,
                source: Source::Unicode(map),
            });
        }
        let std_codes = |table: &[u16; 256]| -> Arc<Vec<u32>> {
            Arc::new(
                table
                    .iter()
                    .map(|&sid| {
                        let name = names::SID_NAMES
                            .get(usize::from(sid))
                            .copied()
                            .unwrap_or("");
                        t.names
                            .iter()
                            .position(|g| g.as_slice() == name.as_bytes())
                            .map_or(0, |g| g as u32)
                    })
                    .collect(),
            )
        };
        let adobe = match &t.encoding {
            type1::Encoding::Standard => Some((
                0,
                Encoding::AdobeStandard,
                Source::Codes(std_codes(&names::STANDARD_ENCODING)),
            )),
            type1::Encoding::Expert => Some((
                1,
                Encoding::AdobeExpert,
                Source::Codes(std_codes(&names::EXPERT_ENCODING)),
            )),
            type1::Encoding::Array { indices, count } => {
                let codes: Vec<u32> = (0..256u32)
                    .map(|c| {
                        if c < *count {
                            u32::from(*indices.get(c as usize).unwrap_or(&0))
                        } else {
                            0
                        }
                    })
                    .collect();
                Some((2, Encoding::AdobeCustom, Source::Codes(Arc::new(codes))))
            }
            type1::Encoding::IsoLatin1 => synthesize_unicode(
                t.names
                    .iter()
                    .cloned()
                    .enumerate()
                    .map(|(g, n)| (g as u32, n)),
            )
            .map(|m| (3, Encoding::AdobeLatin1, Source::Unicode(m))),
            type1::Encoding::None => None,
        };
        if let Some((id, encoding, source)) = adobe {
            charmaps.push(Charmap {
                platform_id: 7,
                encoding_id: id,
                encoding,
                source,
            });
        }
        let bbox = t.bbox;
        let mut face = Face {
            format: Format::Type1,
            num_glyphs: n,
            units_per_em: t.units_per_em,
            ascender: bbox[3] as i16,
            descender: bbox[1] as i16,
            bbox,
            has_glyph_names: true,
            cid_keyed: false,
            charmaps,
            charmap: None,
            bold: t.bold,
            italic: t.italic,
            fixed_width: t.fixed_pitch,
            family_class: None,
            program: Program::Type1(t),
        };
        face.select_default();
        face
    }

    fn from_cff(c: cff::Cff) -> Face {
        let num_glyphs = if c.is_cid {
            c.max_cid() + 1
        } else {
            c.num_glyphs()
        };
        let mut charmaps = Vec::new();
        if !c.is_cid {
            if let Some(map) = synthesize_unicode(
                (0..c.num_glyphs()).filter_map(|g| c.glyph_name(g).map(|n| (g, n))),
            ) {
                charmaps.push(Charmap {
                    platform_id: 3,
                    encoding_id: 1,
                    encoding: Encoding::Unicode,
                    source: Source::Unicode(map),
                });
            }
            if c.encoding_count > 0 {
                let (id, encoding) = match c.encoding_offset {
                    0 => (0, Encoding::AdobeStandard),
                    1 => (1, Encoding::AdobeExpert),
                    _ => (2, Encoding::AdobeCustom),
                };
                charmaps.push(Charmap {
                    platform_id: 7,
                    encoding_id: id,
                    encoding,
                    source: Source::CffCodes,
                });
            }
        }
        let bbox = c.bbox;
        let mut face = Face {
            format: Format::Cff,
            num_glyphs,
            units_per_em: c.units_per_em.min(u32::from(u16::MAX)) as u16,
            ascender: bbox[3] as i16,
            descender: bbox[1] as i16,
            bbox,
            has_glyph_names: !c.is_cid,
            cid_keyed: c.is_cid,
            charmaps,
            charmap: None,
            bold: c.bold,
            italic: c.italic,
            fixed_width: c.fixed_pitch,
            family_class: None,
            program: Program::Cff(Box::new(c)),
        };
        face.select_default();
        face
    }

    /// `find_unicode_charmap`, as FT_Open_Face selects a charmap: a
    /// UCS-4 one from the end, else any Unicode one from the end.
    fn select_default(&mut self) {
        let ucs4 = (0..self.charmaps.len()).rev().find(|&i| {
            let c = &self.charmaps[i];
            c.encoding == Encoding::Unicode
                && ((c.platform_id == 3 && c.encoding_id == 10)
                    || (c.platform_id == 0 && c.encoding_id == 4)
                    || (c.platform_id == 0 && c.encoding_id == 6 && self.cmap_format(i) == 13))
        });
        self.charmap = ucs4.or_else(|| {
            self.charmaps
                .iter()
                .rposition(|c| c.encoding == Encoding::Unicode)
        });
    }

    /// `FT_Select_Charmap(face, FT_ENCODING_UNICODE)`: false when there is
    /// no Unicode charmap.
    pub fn select_unicode(&mut self) -> bool {
        let before = self.charmap;
        self.select_default();
        if self
            .charmap
            .is_some_and(|i| self.charmaps[i].encoding == Encoding::Unicode)
        {
            true
        } else {
            self.charmap = before;
            false
        }
    }

    /// `FT_Get_CMap_Format`: -1 for a charmap that is not an sfnt subtable.
    pub fn cmap_format(&self, i: usize) -> i32 {
        match (&self.program, self.charmaps.get(i).map(|c| &c.source)) {
            (Program::Sfnt(s), Some(Source::Sfnt(t))) => {
                s.subtables.get(*t).map_or(-1, |t| i32::from(t.format))
            }
            _ => -1,
        }
    }

    /// `FT_Get_Char_Index` with the selected charmap.
    pub fn get_char_index(&self, code: u32) -> u32 {
        let Some(cm) = self.charmap.and_then(|i| self.charmaps.get(i)) else {
            return 0;
        };
        let g = match (&cm.source, &self.program) {
            (Source::Sfnt(i), Program::Sfnt(s)) => {
                s.subtables.get(*i).map_or(0, |t| s.char_index(t, code))
            }
            (Source::Unicode(map), _) => unicode_index(map, code),
            (Source::Codes(codes), _) => codes.get(code as usize).copied().unwrap_or(0),
            (Source::CffCodes, Program::Cff(c)) => {
                c.codes.get(code as usize).map_or(0, |&g| u32::from(g))
            }
            _ => 0,
        };
        if g >= self.num_glyphs { 0 } else { g }
    }

    /// MuPDF's `ft_char_index`: the code, then the code in the symbol
    /// area, then a lookalike for U+22EF.
    pub fn char_index(&self, code: u32) -> u32 {
        let mut g = self.get_char_index(code);
        if g == 0 {
            g = self.get_char_index(0xf000u32.wrapping_add(code));
        }
        if g == 0 && code == 0x22ef {
            g = self.get_char_index(0x2026);
        }
        g
    }

    /// `FT_Get_Name_Index`.
    pub fn get_name_index(&self, name: &[u8]) -> u32 {
        match &self.program {
            Program::Sfnt(s) => s.name_index(name),
            Program::Cff(c) => c.name_index(name),
            Program::Type1(t) => t.name_index(name),
        }
    }

    /// MuPDF's `ft_name_index`: the name, then other names of its code
    /// point, then `uniXXXX`.
    pub fn name_index(&self, name: &[u8]) -> u32 {
        let code = self.get_name_index(name);
        if code != 0 {
            return code;
        }
        let unicode = glyphs::unicode(name);
        if unicode == 0 {
            return 0;
        }
        for dup in glyphs::duplicate_names(unicode) {
            let c = self.get_name_index(dup.as_bytes());
            if c != 0 {
                return c;
            }
        }
        self.get_name_index(format!("uni{unicode:04X}").as_bytes())
    }

    /// `FT_Get_Glyph_Name`, None for a face without names.
    pub fn glyph_name(&self, gid: u32) -> Option<Vec<u8>> {
        match &self.program {
            Program::Sfnt(s) => s.glyph_name(gid),
            Program::Cff(c) => c.glyph_name(gid),
            Program::Type1(t) => t.glyph_name(gid),
        }
    }

    /// `FT_Get_Advance` unscaled: the advance in font units, None where
    /// FreeType fails (a glyph that does not exist).
    pub fn advance(&self, gid: u32) -> Option<i64> {
        if gid >= self.num_glyphs {
            return None;
        }
        match &self.program {
            Program::Sfnt(s) if self.format == Format::TrueType => Some(i64::from(s.advance(gid))),
            Program::Sfnt(s) => Some(i64::from(s.advance(gid))),
            Program::Cff(c) => {
                let g = if c.is_cid { c.gid_of_cid(gid) } else { gid };
                c.advance(g).map(|a| a.round() as i64)
            }
            Program::Type1(t) => t.advance(gid),
        }
    }

    /// What `fz_bound_ft_glyph` measures of glyph `gid`: the control box of
    /// its unhinted outline in font units, None for an outline with no
    /// points; an error for a glyph FreeType fails to load. None when the
    /// outline cannot be read here (CFF inside an sfnt).
    pub fn glyph_cbox(
        &self,
        gid: u32,
    ) -> Option<Result<Option<outline::CBox>, outline::LoadError>> {
        Some(match &self.program {
            Program::Sfnt(s) if s.has_glyf || !s.has_cff => match s.glyf() {
                None => Err(outline::LoadError),
                Some(g) => outline::truetype_points(&g, gid).map(|points| {
                    let mut b = outline::Points::default();
                    for (x, y) in points {
                        b.add(x as f64, y as f64);
                    }
                    b.cbox()
                }),
            },
            Program::Sfnt(_) => return None,
            Program::Cff(c) => c.outline_cbox(gid),
            Program::Type1(t) => {
                if gid >= self.num_glyphs {
                    Err(outline::LoadError)
                } else {
                    t.outline_cbox(gid)
                }
            }
        })
    }

    /// `FT_Load_Glyph` with `FT_LOAD_NO_HINTING` at the size MuPDF sets
    /// for rendering (`FT_Set_Char_Size` 65536, at 72 dpi: 1024 pixels an
    /// em): glyph `gid`'s outline in 26.6. None when the outline cannot be
    /// read here (CFF inside an sfnt).
    pub fn glyph_outline(&self, gid: u32) -> Option<Result<outline::Outline, outline::LoadError>> {
        let upem = i64::from(self.units_per_em.max(1));
        let scale = outline::div_fix_int(1024 * 64, upem);
        Some(match &self.program {
            Program::Sfnt(s) if s.has_glyf || !s.has_cff => match s.glyf() {
                None => Err(outline::LoadError),
                Some(g) => outline::truetype_outline(&g, gid, (scale, scale), s.lsb(gid)),
            },
            Program::Sfnt(_) => return None,
            Program::Cff(c) => c.outline(gid).map(|(mut o, top, sub)| {
                // cff_slot_load: a font dictionary's own units scale its
                // glyphs to the top dictionary's.
                let k = if sub != 0 && sub != top {
                    mul_div(scale, i64::from(top), i64::from(sub))
                } else {
                    scale
                };
                o.scale(k, k);
                o
            }),
            Program::Type1(t) => {
                if gid >= self.num_glyphs {
                    Err(outline::LoadError)
                } else {
                    t.outline(gid).map(|mut o| {
                        o.scale(scale, scale);
                        o
                    })
                }
            }
        })
    }

    /// The format string FreeType reports.
    pub fn format_name(&self) -> &'static str {
        match self.format {
            Format::TrueType => "TrueType",
            Format::Type1 => "Type 1",
            Format::Cff => "CFF",
        }
    }
}

/// `fz_lookup_base14_font`: MuPDF's builtin font for a standard name.
/// The metrics of MuPDF's builtin CJK font, Source Han Serif (each of its
/// four faces has the same), as an OpenType font with no glyphs drawn:
/// nupdf does not carry the 25 MB program (DECISIONS D34). Every character
/// maps to glyph 0.
pub fn cjk_metrics() -> Arc<[u8]> {
    static FONT: std::sync::OnceLock<Arc<[u8]>> = std::sync::OnceLock::new();
    FONT.get_or_init(|| {
        let be16 = |v: i32| (v as u16).to_be_bytes();
        let mut head = vec![0u8; 54];
        head[0..4].copy_from_slice(&[0, 1, 0, 0]);
        head[12..16].copy_from_slice(&0x5F0F_3CF5u32.to_be_bytes());
        head[18..20].copy_from_slice(&be16(1000));
        for (i, v) in [-997, -1049, 2929, 1809].into_iter().enumerate() {
            head[36 + 2 * i..38 + 2 * i].copy_from_slice(&be16(v));
        }
        let mut hhea = vec![0u8; 36];
        hhea[0..4].copy_from_slice(&[0, 1, 0, 0]);
        hhea[4..6].copy_from_slice(&be16(1151));
        hhea[6..8].copy_from_slice(&be16(-286));
        hhea[34..36].copy_from_slice(&be16(1));
        let maxp = vec![0, 0, 0x50, 0, 0xff, 0xff];
        let hmtx = vec![0x03, 0xe8, 0, 0];
        // A (3,1) format 4 subtable with only the closing segment.
        let mut cmap = vec![0, 0, 0, 1, 0, 3, 0, 1, 0, 0, 0, 12];
        for v in [4, 24, 0, 2, 2, 0, 0, 0xffff, 0, 0xffff, 1, 0] {
            cmap.extend_from_slice(&be16(v));
        }
        let tables: [(&[u8; 4], Vec<u8>); 6] = [
            // An empty table would be a missing one.
            (b"CFF ", vec![0; 4]),
            (b"cmap", cmap),
            (b"head", head),
            (b"hhea", hhea),
            (b"hmtx", hmtx),
            (b"maxp", maxp),
        ];
        let mut out = b"OTTO".to_vec();
        out.extend_from_slice(&be16(tables.len() as i32));
        out.extend_from_slice(&[0; 6]);
        let mut body = Vec::new();
        for (tag, data) in &tables {
            let offset = 12 + 16 * tables.len() + body.len();
            out.extend_from_slice(*tag);
            out.extend_from_slice(&[0; 4]);
            out.extend_from_slice(&(offset as u32).to_be_bytes());
            out.extend_from_slice(&(data.len() as u32).to_be_bytes());
            body.extend_from_slice(data);
            while body.len() % 4 != 0 {
                body.push(0);
            }
        }
        out.extend_from_slice(&body);
        out.into()
    })
    .clone()
}

